def braille():
    dots = ((0, 0, 1), (1, 0, 2), (2, 0, 4), (3, 0, 64),
            (0, 2, 8), (1, 2, 16), (2, 2, 32), (3, 2, 128))
    width = max(map(len, SOURCE))
    return ["".join(chr(0x2800 + sum(bit for dy, dx, bit in dots
            if y + dy < len(SOURCE) and x + dx < len(SOURCE[y + dy])
            and SOURCE[y + dy][x + dx] == "@"))
            for x in range(0, width, 4)) for y in range(0, len(SOURCE), 4)]
